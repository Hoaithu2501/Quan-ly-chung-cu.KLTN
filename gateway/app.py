"""Same-origin UI and API reverse proxy. No domain data access."""

import ipaddress
from concurrent.futures import ThreadPoolExecutor

import requests
from flask import request, Response, send_from_directory
from shared.config import ROOT, PORTS, service_url
from shared.http import pooled_session
from shared.web import create_app as base_app, run, APIError

ROUTES = {
    "auth": "auth",
    "apartments": "resident",
    "residents": "resident",
    "contracts": "resident",
    "billing": "billing",
    "parking": "parking",
    "maintenance": "maintenance",
    "notifications": "notification",
    "complaints": "complaint",
    "chatbot": "chatbot",
}
WEBHOOK_PATH = "/api/billing/sepay/webhook"
ONE_WEEK = 7 * 24 * 60 * 60
# Inline styles are generated by the UI; scripts never run inline. gstatic serves the Firebase SDK.
CONTENT_SECURITY_POLICY = "; ".join(
    (
        "default-src 'self'",
        "script-src 'self' https://www.gstatic.com",
        "style-src 'self' 'unsafe-inline'",
        "img-src 'self' data: blob:",
        "font-src 'self'",
        "connect-src 'self' https://*.googleapis.com https://www.gstatic.com",
        "worker-src 'self'",
        "object-src 'none'",
        "base-uri 'self'",
        "form-action 'self'",
        "frame-ancestors 'self'",
    )
)


def caller_ip():
    """Cloudflare overwrites this header at its edge, so tunnel callers cannot forge it."""
    try:
        return str(ipaddress.ip_address(request.headers.get("CF-Connecting-IP", "").strip()))
    except ValueError:
        return request.remote_addr or "unknown"


def create_app():
    app = base_app("gateway")

    @app.before_request
    def restrict_tunnel():
        # The website is used on this machine only; the tunnel exists just for the bank callback.
        if "CF-Connecting-IP" in request.headers and request.path != WEBHOOK_PATH:
            raise APIError("Không tìm thấy trang.", 404)

    @app.after_request
    def browser_policy(response):
        if request.path != "/docs":  # Swagger UI needs its own CDN assets and inline bootstrap.
            response.headers["Content-Security-Policy"] = CONTENT_SECURITY_POLICY
        response.headers["Permissions-Policy"] = "camera=(), microphone=(), geolocation=()"
        return response

    @app.route("/api/<path:path>", methods=["GET", "POST", "PATCH", "PUT", "DELETE"])
    def proxy(path):
        service = ROUTES.get(path.split("/")[0])
        if service is None:
            raise APIError("Không tìm thấy API.", 404)
        # Never forward internal service credentials from the public gateway.
        headers = {
            key: request.headers[key]
            for key in ("Authorization", "Content-Type", "Idempotency-Key")
            if key in request.headers
        }
        headers["X-Client-IP"] = caller_ip()
        try:
            upstream = pooled_session(retry_reads=False).request(
                request.method,
                service_url(service) + "/api/" + path,
                params=request.args.to_dict(flat=False),
                data=request.get_data(),
                headers=headers,
                timeout=(3, 45),
                allow_redirects=False,
            )
        except requests.RequestException:
            raise APIError(f"Dịch vụ {service} chưa sẵn sàng. Vui lòng thử lại.", 503)
        selected = {
            key: upstream.headers[key]
            for key in ("Content-Type", "Content-Disposition", "Retry-After")
            if key in upstream.headers
        }
        return Response(upstream.content, status=upstream.status_code, headers=selected)

    @app.get("/api-status")
    def status():
        def check(name):
            try:
                response = requests.get(service_url(name) + "/health", timeout=2)
                return name, "ok" if response.ok else "unavailable"
            except requests.RequestException:
                return name, "unavailable"

        with ThreadPoolExecutor(max_workers=8) as pool:
            results = dict(pool.map(check, PORTS))
        return {"services": results}

    @app.get("/")
    def index():
        return send_from_directory(ROOT / "frontend", "index.html")

    @app.get("/<path:filename>")
    def static_asset(filename):
        # Code revalidates by ETag so a deploy shows at once; images and fonts rarely change.
        return send_from_directory(
            ROOT / "frontend", filename, max_age=ONE_WEEK if filename.startswith("assets/") else None
        )

    return app


app = create_app()
if __name__ == "__main__":
    run(app, 5000)
